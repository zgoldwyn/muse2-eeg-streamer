"""Test pinned upstream PR files in a temporary copy; no checkout changes.

Run from the repository root: python scratch/samuel/verify_math_handoff.py
The commit objects must already be available locally (git fetch origin).
"""

from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[2]
NAMIT = "892ea3c65cf83e00f750315aa056e570dae920b7"
BEN = "07443afbfce8a575b75157e01fdd41f4be1b8b2d"
FIXTURE = Path("tests/fixtures/integration/integration-demo-001")


def main():
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reference-labels", type=Path,
                        help="Existing predeclared labels; none are generated by this script.")
    args = parser.parse_args()
    reference_args = (["--reference-labels", str(args.reference_labels.resolve())]
                      if args.reference_labels else [])
    with tempfile.TemporaryDirectory(prefix="math-handoff-") as temporary:
        target = Path(temporary)
        for folder in ("eeg_app", "tests"):
            shutil.copytree(ROOT / folder, target / folder,
                            ignore=shutil.ignore_patterns("__pycache__"))
        # Use the actual code and writer output byte-for-byte, not imitations.
        for commit, path in ((NAMIT, Path("eeg_app/dataset.py")),
                             (BEN, FIXTURE / "eeg.csv"),
                             (BEN, FIXTURE / "metadata.json")):
            contents = subprocess.check_output(
                ["git", "show", f"{commit}:{path.as_posix()}"], cwd=ROOT,
            )
            destination = target / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(contents)
        print(f"Namit loader: {NAMIT}\nBen fixture: {BEN}", flush=True)
        subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests",
                        "-v"], cwd=target, check=True)
        subprocess.run([sys.executable, "-m", "eeg_app.math_pipeline", str(FIXTURE),
                        "--flatline-tolerance-uv", "0", "--demo-predictions",
                        *reference_args], cwd=target, check=True)


if __name__ == "__main__":
    main()
